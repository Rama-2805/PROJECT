/* ─── Sidebar Component ────────────────────────────────────────── */
export function Sidebar() {
  const [collapsed, setCollapsed] = useState(false);
  const [activePath, setActivePath] = useState("/dashboard");

  return (
    <motion.aside
      className={cn(
        "fixed left-0 top-0 bottom-0 z-40 flex flex-col",
        "bg-white/5 backdrop-blur-[40px] saturate-200 border-r border-white/10",
        "transition-all duration-300 ease-smooth",
      )}
      animate={{ width: collapsed ? 72 : 256 }}
      initial={{ width: 256 }}
    >
      {/* Logo */}
      <div className={cn("flex items-center h-16 border-b border-glass-border shrink-0", collapsed ? "justify-center px-3" : "px-5")}>
        <div className="flex items-center gap-2.5 min-w-0">
          <div className="flex h-8 w-8 shrink-0 items-center justify-center rounded-lg bg-gradient-to-br from-ai-blue to-ai-purple">
            <span className="text-sm font-bold text-white">S</span>
          </div>
          {!collapsed && (
            <motion.span
              initial={{ opacity: 0 }}
              animate={{ opacity: 1 }}
              exit={{ opacity: 0 }}
              className="text-sm font-semibold whitespace-nowrap text-text-primary"
            >
              SmartCampus <span className="gradient-text">AI</span>
            </motion.span>
          )}
        </div>
      </div>

      {/* Role Indicator */}
      <div className={cn("border-b border-glass-border shrink-0", collapsed ? "px-2 py-3" : "px-4 py-3")}>
        <div className={cn("flex items-center gap-2", collapsed && "justify-center")}>
          <span className="h-1.5 w-1.5 rounded-full bg-success animate-glow-pulse shrink-0" />
          {!collapsed && (
            <span className="text-[10px] font-medium text-text-muted uppercase tracking-wider truncate">
              Institution Admin
            </span>
          )}
        </div>
      </div>

      {/* Menu Sections */}
      <nav className="flex-1 overflow-y-auto px-2 py-4 space-y-5 scrollbar-thin">
        {MENU_SECTIONS.map((section) => (
          <div key={section.title}>
            {!collapsed && (
              <p className="px-2 mb-2 text-[10px] font-semibold text-text-muted uppercase tracking-widest">
                {section.title}
              </p>
            )}
            <div className="space-y-0.5">
              {section.items.map((item) => {
                const isActive = activePath === item.href;
                return (
                  <a
                    key={item.href}
                    href={item.href}
                    onClick={(e) => {
                      e.preventDefault();
                      setActivePath(item.href);
                    }}
                    className={cn(
                      "flex items-center gap-3 px-2.5 py-2 rounded-lg text-sm transition-all duration-200 group",
                      collapsed && "justify-center px-0",
                      isActive
                        ? "bg-ai-blue/10 text-ai-blue border border-ai-blue/20"
                        : "text-text-dim hover:text-text-primary hover:bg-glass-light border border-transparent",
                    )}
                    title={collapsed ? item.label : undefined}
                  >
                    <span className={cn("shrink-0", isActive && "text-ai-blue")}>
                      {item.icon}
                    </span>
                    {!collapsed && (
                      <>
                        <span className="truncate">{item.label}</span>
                        {item.badge && (
                          <span className="ml-auto text-[9px] font-bold px-1.5 py-0.5 rounded-full bg-success/20 text-success uppercase">
                            {item.badge}
                          </span>
                        )}
                      </>
                    )}
                  </a>
                );
              })}
            </div>
          </div>
        ))}
      </nav>

      {/* Collapse Toggle */}
      <div className="border-t border-glass-border p-3 shrink-0">
        <button
          onClick={() => setCollapsed(!collapsed)}
          className={cn(
            "flex items-center justify-center w-full py-2 rounded-lg text-text-dim hover:text-text-primary hover:bg-glass-light transition-all",
            collapsed && "flex-col",
          )}
          aria-label={collapsed ? "Expand sidebar" : "Collapse sidebar"}
        >
          <svg
            className={cn("w-4 h-4 transition-transform duration-300", collapsed ? "rotate-180" : "")}
            fill="none"
            viewBox="0 0 24 24"
            stroke="currentColor"
            strokeWidth={2}
          >
            <path strokeLinecap="round" strokeLinejoin="round" d="M11 19l-7-7 7-7m8 14l-7-7 7-7" />
          </svg>
          {!collapsed && <span className="ml-2 text-xs">Collapse</span>}
        </button>
      </div>
    </motion.aside>
  );
}
